"""Erzeugt src/font5x7.c: 5x7-Schrift fuer das Dot-Matrix-Display.

Jede Zeichenvorlage hat 7 Zeilen mit je 5 Zeichen ('#' = Punkt an).
Im C-Code ist jede Zeile ein Byte, Bit 4 = linke Spalte.
"""
